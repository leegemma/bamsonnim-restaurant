import fs from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..'),dir=path.join(root,'public/assets/zombies');
function normalize(meta){
 const frames=meta.walkFrames;
 return{key:meta.key,actorId:meta.actorId,name:meta.name||`${meta.actorId} · 네 방향 걷기·앉기`,url:meta.url,
  width:meta.width,height:meta.height,type:'directional-atlas',trim:false,lockHeads:!!meta.headStabilization||!!meta.lockHeads,
  referenceHeight:meta.referenceHeight,fps:meta.fps||7,walkFrames:frames,status:'verified',cols:frames+1,rows:4,
  frames:{walk:Array.from({length:frames},(_,i)=>i),sit:frames,idle:0},sequence:meta.sequence||meta.walkSequence||(frames===3?[0,1,0,2]:Array.from({length:frames},(_,i)=>i)),
  directions:meta.directions||['오른쪽 아래','왼쪽 아래','왼쪽 위 · 뒷모습','오른쪽 위 · 뒷모습'].map((name,i)=>({id:['se','sw','nw','ne'][i],name,row:i,index:i})),
  poses:meta.poses.map((pose,i)=>({index:i,row:pose.dir??Math.floor(i/(frames+1)),column:i%(frames+1),dir:pose.dir??Math.floor(i/(frames+1)),
   state:pose.state,frame:pose.frame,source:pose.source,bounds:pose.bounds,anchor:pose.anchor,...(pose.hip?{hip:pose.hip}:{}),
   ...(pose.headPolygon?{headPolygon:pose.headPolygon,neckAnchor:pose.neckAnchor}:{}),...(pose.companions?{companions:pose.companions}:{})}))};
}

const files=await fs.readdir(dir).catch(()=>[]),records=[];
for(const filename of files.filter(n=>n.endsWith('.json')).sort()){
 const meta=JSON.parse(await fs.readFile(path.join(dir,filename),'utf8'));
 if(meta.status!=='verified')continue;
 if(!meta.actorId||!meta.key||!meta.url||!Array.isArray(meta.poses)||![3,4,8].includes(meta.walkFrames)||meta.poses.length!==4*(meta.walkFrames+1))throw Error(`Invalid directional metadata: ${filename}`);
 await fs.access(path.join(root,'public',meta.url));
 records.push(normalize(meta));
}
const base=await fs.readFile(path.join(root,'public/assets/wanderer-shuffle.json'),'utf8').then(JSON.parse).catch(()=>null);
if(base?.status==='verified'&&!records.some(r=>r.actorId==='wanderer'))records.unshift(normalize(base));
if(new Set(records.map(r=>r.actorId)).size!==records.length)throw Error('Duplicate actor directional sheets');
await fs.writeFile(path.join(root,'src/zombie-atlases.generated.js'),'// Generated by scripts/update-zombie-atlases.mjs from verified atlas metadata.\nexport const ZOMBIE_ATLASES='+JSON.stringify(records,null,2)+';\n');
console.log(JSON.stringify({registered:records.length,actors:records.map(r=>r.actorId)}));
